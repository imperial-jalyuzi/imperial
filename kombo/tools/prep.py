"""Prepare kombo catalog images. python3 tools/prep.py  (reads MANIFEST below, writes img/<col>/...)"""
import numpy as np
from PIL import Image
A = '/mnt/user-data/attachments/29c18e40-edfd-55e7-a3e1-da5539b3418b/'
import json
M = json.load(open('tools/manifest.json'))

def label_top(im):
    """Bottom white rail of the blind; crop a little below it (drops the code label)."""
    a = np.asarray(im.convert('L')).astype(float); h, w = a.shape
    band = a[:, int(w * .2):int(w * .8)].mean(1)
    ys = [y for y in range(int(h * .7), int(h * .93)) if band[y] > 185]
    return (max(ys) + 40) if ys else int(h * .86)

import os, sys
out = []
for c in M['collections']:
    col, sheet = c['id'], c['sheet']
    os.makedirs(f'img/{col}', exist_ok=True)
    room = c.get('style') == 'room'
    if sheet:
        Image.open(A + sheet + '-image.jpg').convert('RGB').save(f'img/{col}/namuna.jpg', quality=84, optimize=True)
    its = []
    for code, f, tag, desc in c['items']:
        im = Image.open(A + f + '-image.jpg').convert('RGB'); w, h = im.size
        lt = int(h * .855) if room else label_top(im)
        top = im.crop((0, 0, w, lt))
        th = round(720 * top.height / w)
        top.resize((720, round(720 * top.height / w)), Image.LANCZOS).save(f'img/{col}/tayyor_{code}.jpg', quality=80, optimize=True)
        sq, x, y = (int(w * .36), int(w * .14), int(h * .40)) if room else (int(w * .46), (w - int(w * .46)) // 2, int(h * .23))
        im.crop((x, y, x + sq, y + sq)).resize((480, 480), Image.LANCZOS).save(f'img/{col}/mato_{code}.jpg', quality=84, optimize=True)
        its.append({'code': code, 'tag': tag, 'd': desc, 'h': th})
    out.append({'id': col, 'code': c['code'], 'name': c['name'], 'items': its, 'sheet': bool(sheet)})
open('data.js', 'w').write('// Generated by tools/prep.py from tools/manifest.json\nwindow.KATALOG = ' + json.dumps({'colors': M['colors'], 'collections': out}, ensure_ascii=False) + ';\n')
print(sum(len(c['items']) for c in out), 'items')
